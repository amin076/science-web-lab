import assert from "node:assert/strict";
import {createCompoundPendulumComparison,COMPARISON_PARAMETER_SCHEMA,
 COMPARISON_DEFAULTS,panePatch,paneConfig
} from "../src/simulations/subjects/physics/mechanics/compound-pendulum/comparisonModel.js";

assert.ok(Object.keys(COMPARISON_PARAMETER_SCHEMA.properties).length>100);
assert.equal(COMPARISON_DEFAULTS.paneCount,2);
const model=createCompoundPendulumComparison();
assert.equal(model.snapshot().paneCount,2);
assert.equal(model.snapshot().pendulums.length,2);
assert.equal(model.snapshot().pendulums[0].rodCount,4);
assert.equal(panePatch(2,{rodCount:3,lengthM1:1.1}).p2_rodCount,3);
assert.equal(paneConfig(COMPARISON_DEFAULTS,2).initialOmegaRadps1,15.05);
model.configure({paneCount:4,p3_rodCount:3,p4_rodCount:2});
assert.equal(model.snapshot().paneCount,4);
assert.deepEqual(model.snapshot().pendulums.map(x=>x.rodCount),[4,4,3,2]);
const aBefore=model.getParameters().p1_lengthM1;
model.configure({p2_lengthM1:1.73});
assert.equal(model.getParameters().p1_lengthM1,aBefore);
assert.equal(model.getParameters().p2_lengthM1,1.73);
assert.equal(model.snapshot().timeSeconds,0);
model.step(1/240);
assert.ok(model.snapshot().pendulums.every(p=>Math.abs(p.timeSeconds-1/240)<1e-10));
model.configure({selectedPane:3});
assert.ok(model.snapshot().timeSeconds>0);
model.configure({p3_trace1:false});
assert.ok(model.snapshot().timeSeconds>0);
assert.throws(()=>model.configure({p3_lengthM1:0}),RangeError);
assert.throws(()=>model.configure({paneCount:5}),RangeError);
assert.throws(()=>model.configure({selectedPane:5}),RangeError);
assert.throws(()=>model.trajectory({paneIndex:5,rodIndex:1}),RangeError);
assert.ok(model.trajectory({paneIndex:2,rodIndex:1,limit:100}).length>0);
const near=model.getParameters();
const equal=Object.fromEntries(Object.entries(paneConfig(near,1)).map(([k,v])=>["p2_"+k,v]));
model.configure(equal);
for(let i=0;i<240;i++)model.step(1/240);
const snap=model.snapshot();
const a=snap.pendulums[0],b=snap.pendulums[1];
assert.deepEqual(a.anglesRad,b.anglesRad);
assert.deepEqual(a.omegasRadps,b.omegasRadps);
assert.equal(snap.comparisons[0].tipSeparationM,0);
model.configure({p2_initialAngleDeg1:model.getParameters().p2_initialAngleDeg1+0.1});
for(let i=0;i<240;i++)model.step(1/240);
assert.ok(model.snapshot().comparisons[0].tipSeparationM>0.00001);
model.clearTrails({paneIndex:2});
assert.equal(model.trajectory({paneIndex:2,rodIndex:1}).length,1);
model.configure({paneCount:1});
assert.equal(model.snapshot().pendulums.length,1);
assert.equal(model.snapshot().timeSeconds,0);
model.dispose();
assert.throws(()=>model.snapshot(),/DISPOSED/);
console.log("Comparison physics API: 1..4 independent systems, matching trajectories, perturbations, synchronized time and lifecycle PASS");
