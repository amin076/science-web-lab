import assert from 'node:assert/strict';
import fs from 'node:fs';
import Handlebars from 'handlebars';
import { advanceStandard2d, sampleStandard2d, standard2dParameters } from '../src/components/simulation-ui/standard2dModel.js';
let state = sampleStandard2d(0);
for (let i = 0; i < 400; i++) state = advanceStandard2d(state, 0.01, 1);
assert.ok(Math.abs(state.time - 4) < 1e-10);
assert.ok(Math.abs(state.x ** 2 + state.y ** 2 - 1) < 1e-12);
assert.equal(advanceStandard2d(sampleStandard2d(0), 100, 2).time, 0.1);
assert.throws(() => advanceStandard2d(state, NaN, 1));
assert.throws(() => advanceStandard2d(state, -1, 1));
assert.equal(standard2dParameters.zoom.minimum, 0.5);
const template = fs.readFileSync('plop-templates/simulation/Simulation.jsx.hbs', 'utf8');
const output = Handlebars.compile(template)({ componentName: 'ReferenceTest', title: 'Reference test', registryKey: 'test.reference' });
assert.match(output, /function ReferenceTest/);
assert.ok(!output.includes('{{'));
const { transform } = await import('esbuild');
await transform(output, { loader: 'jsx' });
console.log('2D model determinism, dt bounds, invariants and editable JSX scaffold passed.');
