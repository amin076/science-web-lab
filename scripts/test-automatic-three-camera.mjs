import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {createThreeCameraSessionAdapter} from "../functions/control/threeCameraSessionAdapter.mjs";
import cameraIds from "../functions/control/data/threeCameraIds.generated.json" with {type:"json"};
const require=createRequire(import.meta.url);
const {transformOrbitControls}=require("./auto-orbit-controls-transform.cjs");
const {discoverThreeCameraIds}=require("./discover-three-camera-simulations.cjs");
const catalog=require("../functions/api/data/platformCatalog.generated.json");

const found=discoverThreeCameraIds(catalog);
assert(found.includes("physics.mechanics.gyroscope"),"Gyroscope must be automatically supported");
assert(found.includes("astronomy.space.earth-orbit-lab"),"3D orbit lab must be supported");
assert(found.includes("physics.electricity.coulomb-law-3d"),"Shared canvas should be supported");
assert(!found.includes("astronomy.space.solar-system"),"Solar uses existing model session");
assert(!found.includes("evolution-of-life"),"Timeline must be excluded");
assert(!found.includes("physics.mechanics.gearbox-differential-3d"),"Quarantined lab must be excluded");
assert.deepEqual(cameraIds,found,"Generated camera registry must match current source inspection");
const input='import { Environment, OrbitControls } from "@react-three/drei";';
const result=transformOrbitControls(input,"/project/src/simulations/subjects/physics/mechanics/gyroscope/GyroscopeSimulation.jsx");
assert(result.code.includes("AutoOrbitControls as OrbitControls"));
assert(result.code.includes('import { Environment } from "@react-three/drei"'));
assert.equal(transformOrbitControls(input,"/project/src/simulations/subjects/astronomy/space/solar-system/index.jsx"),null);
assert.equal(transformOrbitControls(input,"/project/src/simulations/subjects/physics/mechanics/projectile/index.jsx")?.code.includes("AutoOrbitControls"),true);
let adapter=createThreeCameraSessionAdapter("physics.mechanics.gyroscope");
let doc=adapter.create();
const initial=adapter.execute(doc,{action:"get_state"});
assert.equal(initial.mutation,false);
assert.throws(()=>adapter.create({mass:10}),/camera sessions only/);
assert.throws(()=>adapter.execute(doc,{action:"set_camera",camera:{yawDegrees:361}}),/Invalid/);
const move=adapter.execute(doc,{action:"set_camera",camera:{yawDegrees:360,durationSeconds:10,easing:"easeInOut"}});
assert.equal(move.document.camera.yawDegrees,360);
assert.equal(move.document.camera.durationSeconds,10);
assert.equal(move.document.revision,1);
assert.equal(move.result.state.camera.yawDegrees,360);
console.log("Discovered "+found.length+" 3D camera simulations; generic camera session tests PASS");
