import assert from "node:assert/strict";
import fs from "node:fs";
import {WAVE_ID,WAVE_SCHEMA,WAVE_DEFAULTS,createWaveStringModel} from "../src/esbiko-physics/waves/stringWaveModel.js";
import {WAVE_DESCRIPTOR,createWaveControlDocument,exposeWaveControlState,executeWaveControlCommand}
 from "../functions/control/waveStringControl.mjs";
import {requireSimulationControlAdapter,listSimulationControlAdapters} from "../functions/control/adapterRegistry.mjs";

assert.equal(WAVE_DESCRIPTOR.id,WAVE_ID);
assert.equal(WAVE_SCHEMA.properties.visibleCount.maximum,4);
assert.equal(WAVE_SCHEMA.properties.s4_rightShape.enum.includes("composite"),true);
assert.equal(WAVE_DESCRIPTOR.supportedMedia.browserCanvasWebM,true);
assert.equal(WAVE_DESCRIPTOR.supportedMedia.serverVideoCapture,false);
assert.ok(listSimulationControlAdapters().some(x=>x.id===WAVE_ID));
assert.equal(requireSimulationControlAdapter(WAVE_ID).descriptor.id,WAVE_ID);
assert.ok(WAVE_DESCRIPTOR.commands.includes("fire"));
const waves=createWaveStringModel({visibleCount:2,s1_mode:"dual",s1_shape:"composite",s1_rightShape:"ricker"});
let state=waves.snapshot();
assert.equal(state.visibleCount,2);
assert.equal(state.strings.length,4);
waves.configure({s1_tension:32,s1_mu:.5,s2_mass:6});
state=waves.snapshot();
assert.ok(Math.abs(state.strings[0].speed-8)<1e-10);
assert.ok(Math.abs(state.strings[1].mu-.5)<1e-10);
assert.equal(state.strings[0].wavelength,state.strings[0].speed/state.strings[0].freq);
assert.throws(()=>waves.configure({s1_mode:"invalid"}),/Invalid parameter/);
assert.throws(()=>waves.configure({s1_tension:Infinity}),/Invalid parameter/);
assert.throws(()=>waves.configure({prototype_poison:1}),/Unknown parameter/);
waves.step(1);
const snapshot=waves.snapshot(),cp=waves.checkpoint();
const restored=createWaveStringModel();restored.restore(cp);
assert.deepEqual(restored.snapshot(),snapshot);
assert.deepEqual(restored.trajectory({paneIndex:1,limit:71}),waves.trajectory({paneIndex:1,limit:71}));
const before=waves.trajectory({paneIndex:1,limit:61});
assert.ok(before.every(row=>row.length===4&&row.every(Number.isFinite)));
assert.ok(before.some(row=>Math.abs(row[1])>1e-5));
const fireCount=waves.snapshot().strings[0].pulseCount;
waves.trigger(1);
assert.ok(waves.snapshot().strings[0].pulseCount>fireCount);
assert.throws(()=>waves.trigger(5),/String must/);
const altered=structuredClone(cp);altered.timeSeconds=Infinity;
assert.throws(()=>restored.restore(altered),/Malformed/);

let doc=createWaveControlDocument({visibleCount:4,s4_mode:"dual",s4_shape:"chirp"});
const action=(name,request={})=>{
 const value=executeWaveControlCommand(doc,{action:name,...request});
 doc=value.document;return value;
};
assert.equal(doc.revision,0);
assert.equal(action("get_state").mutation,false);
assert.equal(action("get_capabilities").result.schema.properties.s3_mu.minimum,.05);
assert.equal(action("configure",{parameters:{s4_mu:.4,s4_tension:25,s4_rightShape:"triangle"}}).mutation,true);
assert.ok(Math.abs(exposeWaveControlState(doc).state.strings[3].speed-Math.sqrt(25/.4))<1e-10);
action("play");assert.equal(doc.running,true);
action("advance",{seconds:1});assert.ok(Math.abs(doc.checkpoint.timeSeconds-1)<1e-8);
const points=action("get_trajectory",{paneIndex:4,limit:80});
assert.equal(points.mutation,false);assert.equal(points.result.pointsM.length,80);
assert.equal(points.result.columns[1],"totalDisplacementM");
const unchanged=doc.revision;action("get_state");assert.equal(doc.revision,unchanged);
const after=action("fire",{paneIndex:4});
assert.ok(after.result.state.strings[3].pulseCount>0);
assert.throws(()=>action("configure",{parameters:{s4_freq:100}}),/Invalid parameter/);
assert.throws(()=>action("advance",{seconds:3}),/Advance seconds/);
assert.throws(()=>action("open_secret"),/Unsupported wave action/);
action("pause");assert.equal(doc.running,false);
action("reset");assert.equal(doc.checkpoint.timeSeconds,0);
const exact=createWaveControlDocument(WAVE_DEFAULTS);
const e1=executeWaveControlCommand(exact,{action:"advance",seconds:.5});
const e2=executeWaveControlCommand(exact,{action:"advance",seconds:.5});
assert.deepEqual(e1.result.state,e2.result.state);

