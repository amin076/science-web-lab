 await no(setDoc(doc(student,'classes/student-owned'),cls('student')));
 await no(updateDoc(doc(teacher,'classes/public'),{teacherId:'other'}));
 await no(updateDoc(doc(teacher,'classes/public'),{name:123}));
 await no(updateDoc(doc(teacher,'classes/public'),{description:'x'.repeat(4001)}));
 await no(updateDoc(doc(teacher,'classes/public'),{approvedStudents:['other']}));
 await no(getDocs(collection(student,'classes')));
