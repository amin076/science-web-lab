 await yes(setDoc(doc(student,'classes/public/students/student'),member('student')));
 await yes(setDoc(doc(teacher,'classes/private/students/student'),member('student')));
 await yes(getDoc(doc(student,'classes/private')));
 await yes(getDocs(query(collectionGroup(student,'students'),where('uid','==','student'))));
 await no(getDocs(collectionGroup(student,'students')));
 await no(getDoc(doc(other,'classes/public/students/student')));
 await no(setDoc(doc(student,'classes/missing/students/student'),member('student')));
 await env.withSecurityRulesDisabled(async c=>{
  const seed=c.firestore();
  await setDoc(doc(seed,'classes/legacy'),{...cls('teacher',false),pendingStudents:['other'],approvedStudents:['student']});
  await setDoc(doc(seed,'classes/private/experiments/e'),{title:'Exercise'});
 });
 await yes(getDocs(query(collection(student,'classes'),where('approvedStudents','array-contains','student'))));
 await yes(getDoc(doc(student,'classes/legacy')));
 const batch=writeBatch(teacher);batch.set(doc(teacher,'classes/legacy/students/other'),member('other'));batch.update(doc(teacher,'classes/legacy'),{pendingStudents:arrayRemove('other')});await yes(batch.commit());
 await yes(getDoc(doc(other,'classes/legacy')));
 const storage=uid=>env.authenticatedContext(uid).storage();
 const file=ref(storage('teacher'),'attachments/private/e/a.pdf');
 await yes(uploadBytes(file,new Uint8Array([1,2,3]),{contentType:'application/pdf'}));
 await yes(getBytes(ref(storage('student'),'attachments/private/e/a.pdf')));
 await no(getBytes(ref(storage('other'),'attachments/private/e/a.pdf')));
 await no(uploadBytes(ref(storage('student'),'attachments/private/e/x.pdf'),new Uint8Array([1]),{contentType:'application/pdf'}));
 await no(uploadBytes(ref(storage('teacher'),'attachments/private/e/x.html'),new Uint8Array([1]),{contentType:'text/html'}));
