import fs from 'node:fs';
import {initializeTestEnvironment,assertSucceeds as allow,assertFails as deny} from '@firebase/rules-unit-testing';
import {doc,setDoc,getDoc,updateDoc,deleteDoc,collection,collectionGroup,query,where,getDocs,serverTimestamp,writeBatch,arrayRemove} from 'firebase/firestore';
import {ref,uploadBytes,getBytes,deleteObject} from 'firebase/storage';
